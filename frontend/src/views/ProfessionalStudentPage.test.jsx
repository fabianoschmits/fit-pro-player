// @vitest-environment happy-dom
import React,{act} from 'react'
import {createRoot} from 'react-dom/client'
import {MemoryRouter,Routes,Route} from 'react-router-dom'
import {beforeEach,afterEach,it,expect,vi} from 'vitest'
const mocks=vi.hoisted(()=>({repo:{clientDetail:vi.fn(),studentNote:vi.fn(),studentPlanDraft:vi.fn(),executionPage:vi.fn(),studentNotes:vi.fn(),addStudentNote:vi.fn()}}))
vi.mock('../auth/AuthProvider.jsx',()=>({useAuth:()=>({user:{id:'pro'}})}))
vi.mock('../lib/professional-workflow.js',()=>({createProfessionalWorkflowRepository:()=>mocks.repo}))
import ProfessionalStudentPage from './ProfessionalStudentPage.jsx'
import {useUI} from '../store/useUI.js'
let root,container
beforeEach(()=>{globalThis.IS_REACT_ACT_ENVIRONMENT=true;mocks.repo.clientDetail.mockResolvedValue({displayName:'Ana',assignments:[],executions:[]});mocks.repo.studentNote.mockResolvedValue({body:'Privado'});mocks.repo.studentNotes.mockResolvedValue([{id:'legacy-note',body:'Privado',createdAt:'2026-10-20T12:30:00Z'}]);mocks.repo.addStudentNote.mockResolvedValue({id:'new-note',body:'Nova anotação',createdAt:'2026-10-28T12:34:00Z'});mocks.repo.studentPlanDraft.mockResolvedValue(null);mocks.repo.executionPage.mockResolvedValue({items:[],total:0,offset:0,hasMore:false});container=document.createElement('div');root=createRoot(container)})
afterEach(async()=>{await act(async()=>root.unmount());vi.clearAllMocks()})
const render=()=>act(async()=>root.render(<MemoryRouter initialEntries={['/professional/students/s']}><Routes><Route path="/professional/students/:studentId" element={<ProfessionalStudentPage/>}/></Routes></MemoryRouter>))
const fillTextArea=(textarea,value)=>{Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(textarea,value);textarea.dispatchEvent(new Event('input',{bubbles:true}))}
it('opens the linked student and leads directly to their plan',async()=>{await render();expect(container.textContent).toContain('Ana');expect(container.querySelector('a[href="/professional/students/s/plan"]')).not.toBeNull();expect(container.querySelector('select')).toBeNull();expect(mocks.repo.clientDetail).toHaveBeenCalledWith('s')})
it('loads student executions on profile entry and expands actual workout details with duration',async()=>{
 mocks.repo.executionPage.mockResolvedValueOnce({items:[{id:'execution',dayKey:'monday',status:'completed',startedAt:'2026-10-28T10:00:00Z',completedAt:'2026-10-28T10:30:00Z',programTitle:'Força',prescriptionSnapshot:{workoutTitle:'Treino A',exercises:[{exerciseId:'0025',sets:3,reps:8}]},payload:{entries:[{id:'0025',sets:[{done:true,w:20,r:8}]}]}}],total:1,offset:0,hasMore:false})
 await render()
 expect(mocks.repo.executionPage).toHaveBeenCalledWith({studentId:'s'})
 expect(container.querySelector('button')?.textContent).not.toContain('Histórico')
 const card=container.querySelector('.professional-execution-card')
 expect(card).not.toBeNull()
 expect(card.textContent).toContain('Supino com barra')
 await act(async()=>card.querySelector('summary').click())
 expect(card.textContent).toContain('Realizado')
 expect(card.textContent).toContain('Duração realizada (min): 30')
})
it('loads the next execution page only when requested',async()=>{
 mocks.repo.executionPage.mockResolvedValueOnce({items:[{id:'one',dayKey:'monday',status:'abandoned',startedAt:'2026-10-28T10:00:00Z',payload:{entries:[]}}],total:2,offset:0,hasMore:true}).mockResolvedValueOnce({items:[{id:'two',dayKey:'tuesday',status:'completed',startedAt:'2026-10-27T10:00:00Z',payload:{entries:[]}}],total:2,offset:1,hasMore:false})
 await render()
 expect(container.querySelectorAll('.professional-execution-card')).toHaveLength(1)
 await act(async()=>container.querySelector('button[aria-label="Carregar mais treinos"]').click())
 expect(mocks.repo.executionPage).toHaveBeenLastCalledWith({studentId:'s',offset:1})
 expect(container.querySelectorAll('.professional-execution-card')).toHaveLength(2)
})
it('shows a retry action when automatic execution history loading fails',async()=>{
 mocks.repo.executionPage.mockRejectedValueOnce(new Error('network')).mockResolvedValueOnce({items:[],total:0,offset:0,hasMore:false})
 await render()
 expect(container.textContent).toContain('Não foi possível carregar o histórico de treinos.')
 await act(async()=>container.querySelector('button[aria-label="Tentar carregar histórico"]').click())
 expect(mocks.repo.executionPage).toHaveBeenCalledTimes(2)
})
it('shows current body data and opens the full profile with dated history',async()=>{
 mocks.repo.clientDetail.mockResolvedValueOnce({displayName:'Ana',profile:{heightCm:170,birthDate:'1990-01-01',goal:'build_muscle',experience:'beginner'},weightHistory:[{id:'w',measured_on:'2026-10-20',weight_kg:68.5}],measurements:[],assignments:[],executions:[]})
 await render()
 expect(container.textContent).toContain('1,70 m')
 expect(container.textContent).toContain('68,5 kg')
 expect(container.querySelector('.professional-student-identity').tagName).toBe('SECTION')
 expect(container.querySelector('button[aria-label="Ver perfil completo de Ana"]').textContent).toContain('Expandir')
 await act(async()=>container.querySelector('button[aria-label="Ver perfil completo de Ana"]').click())
 const sheet=useUI.getState().sheets.at(-1)
 expect(sheet).toBeDefined()
 await act(async()=>root.render(sheet.render(()=>{})))
 expect(container.textContent).toContain('Ganhar massa muscular')
 expect(container.textContent).toContain('Histórico de peso')
 expect(container.textContent).toContain('20 de out. de 2026')
 useUI.setState({sheets:[]})
})
it('keeps absent profile data explicit and shows empty histories',async()=>{
 await render()
 expect(container.textContent).toContain('Não informado')
 await act(async()=>container.querySelector('button[aria-haspopup="dialog"]').click())
 const sheet=useUI.getState().sheets.at(-1)
 await act(async()=>root.render(sheet.render(()=>{})))
 expect(container.textContent).toContain('Nenhum peso registrado.')
 expect(container.textContent).toContain('Nenhuma medida registrada.')
 useUI.setState({sheets:[]})
})
it('indicates unsent changes and keeps private notes in their own section',async()=>{mocks.repo.studentPlanDraft.mockResolvedValueOnce({title:'ABC',revision:2,sent_revision:1});await render();expect(container.textContent).toContain('Alterações não enviadas');expect(container.querySelector('.professional-private-note').textContent).toContain('Privado');expect(container.querySelector('textarea[aria-label="Nova anotação privada"]').value).toBe('')})
it('does not show student data after a forbidden read',async()=>{mocks.repo.clientDetail.mockRejectedValueOnce(new Error('42501'));await render();expect(container.querySelector('[role="alert"]')).not.toBeNull();expect(container.querySelector('textarea')).toBeNull()})
it('opens private notes through the profile navigation without losing the loaded draft',async()=>{
 await render()
 const link=container.querySelector('a[href="/professional/students/s?section=notes"]')
 expect(link).not.toBeNull()
 await act(async()=>link.dispatchEvent(new MouseEvent('click',{bubbles:true,button:0})))
 const notes=container.querySelector('.professional-private-notes')
 expect(notes.hidden).toBe(false)
 expect(notes.textContent).toContain('Privado')
 expect(container.querySelector('textarea[aria-label="Nova anotação privada"]').value).toBe('')
})
it('appends a private note below the composer with its saved date and time',async()=>{
 await render()
 const link=container.querySelector('a[href="/professional/students/s?section=notes"]')
 await act(async()=>link.dispatchEvent(new MouseEvent('click',{bubbles:true,button:0})))
 expect(mocks.repo.studentNotes).toHaveBeenCalledWith('s')
 expect(container.textContent).toContain('Privado')
 const composer=container.querySelector('textarea[aria-label="Nova anotação privada"]')
 expect(composer).not.toBeNull()
 await act(async()=>fillTextArea(composer,'Nova anotação'))
 await act(async()=>container.querySelector('button[aria-label="Enviar anotação privada"]').click())
 expect(mocks.repo.addStudentNote).toHaveBeenCalledWith({studentId:'s',body:'Nova anotação'})
 expect(container.textContent).toContain('Nova anotação')
 const timestamp=new Date('2026-10-28T12:34:00Z').toLocaleString('pt-BR',{dateStyle:'short',timeStyle:'short'})
 expect(container.textContent).toContain(timestamp)
 expect(container.querySelector('textarea[aria-label="Nova anotação privada"]').value).toBe('')
})
it('keeps the private note draft after the save request fails',async()=>{
 mocks.repo.addStudentNote.mockRejectedValueOnce(new Error('network'))
 await render()
 const link=container.querySelector('a[href="/professional/students/s?section=notes"]')
 await act(async()=>link.dispatchEvent(new MouseEvent('click',{bubbles:true,button:0})))
 const composer=container.querySelector('textarea[aria-label="Nova anotação privada"]')
 await act(async()=>fillTextArea(composer,'Tentar novamente'))
 await act(async()=>container.querySelector('button[aria-label="Enviar anotação privada"]').click())
 expect(container.querySelector('textarea[aria-label="Nova anotação privada"]').value).toBe('Tentar novamente')
 expect(container.textContent).toContain('Não foi possível salvar a anotação.')
})
