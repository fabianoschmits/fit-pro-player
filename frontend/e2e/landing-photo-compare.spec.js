import { test, expect } from '@playwright/test'

test('public landing demonstrates comparison without account access or photo uploads', async ({ page }) => {
  const privateRequests = []
  page.on('request', request => {
    if (/body_progress_photos|body-progress-photo-cleanup|\/pose\//.test(request.url())) privateRequests.push(request.url())
  })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: 'Aceitar', exact: true }).click()
  const section = page.locator('#evolucao-fotografica')
  await section.scrollIntoViewIfNeeded()
  const slider = section.getByRole('slider', { name: 'Divisor antes e depois' })
  await expect(slider).toHaveAttribute('aria-valuenow', '50')
  await expect.poll(() => section.locator('.bp-photo-stage img').evaluateAll(images => images.length === 2 && images.every(image => image.complete && image.naturalWidth > 0))).toBe(true)
  const geometry = await section.locator('.bp-photo-stage img').evaluateAll(images => images.map(image => image.getAttribute('style')))
  await slider.focus()
  await slider.press('ArrowRight')
  await expect(slider).toHaveAttribute('aria-valuenow', '52')
  const bounds = await slider.boundingBox()
  const stage = await section.locator('.bp-photo-stage').boundingBox()
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  await page.mouse.down()
  await page.mouse.move(stage.x + stage.width * .8, bounds.y + bounds.height / 2, { steps: 12 })
  await page.mouse.up()
  expect(Number(await slider.getAttribute('aria-valuenow'))).toBeGreaterThan(75)
  expect(await section.locator('.bp-photo-stage img').evaluateAll(images => images.map(image => image.getAttribute('style')))).toEqual(geometry)
  await section.getByRole('button', { name: 'Feminino', exact: true }).click()
  await expect(slider).toHaveAttribute('aria-valuenow', '50')
  await expect(section.locator('img').first()).toHaveAttribute('alt', 'Modelo feminino ilustrativo antes')
  await expect(section.locator('input, select')).toHaveCount(0)
  await expect(section.getByRole('button', { name: /Adicionar|Salvar|Editar/ })).toHaveCount(0)
  expect(privateRequests).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await section.screenshot({ path: test.info().outputPath('landing-photo-compare.png') })
  await expect(page.getByRole('heading', { name: 'Do plano ao próximo resultado.' })).toBeVisible()
})
