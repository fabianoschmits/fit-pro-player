test('foreground week rollover advances only the current selection', async ({ page }) => {
  await seed(page, { state: weeklyState() }); await page.goto('/#/progress/weekly')
  await expect(page).toHaveURL(/week=2026-11-16/)
  await page.clock.setFixedTime(new Date('2026-11-23T12:00:00Z'))
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(page).toHaveURL(/week=2026-11-23/)
  await page.getByRole('button', { name: 'Semana anterior', exact: true }).click()
  await expect(page).toHaveURL(/week=2026-11-16/)
  await expect(page.getByRole('textbox', { name: 'Selecionar semana', exact: true })).toHaveValue('2026-11-16')
  await page.clock.setFixedTime(new Date('2026-11-30T12:00:00Z'))
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(page).toHaveURL(/week=2026-11-16/)
})

