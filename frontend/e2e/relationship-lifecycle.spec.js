import { test, expect } from '@playwright/test'
import { seed, stateFixture, USER, STUDENT, openMainNavigation } from './fixtures.test.js'
import { createLifecycleBrowserDatabase } from '../../scripts/lifecycle-browser-database.mjs'

const personalRoutine = '11030300-0000-4000-8000-000000000010'
const tab = (page, name) => page.getByRole('group', { name: 'Escolher plano', exact: true }).getByRole('button', { name, exact: true })
test('real SQL: student request, professional decision, prescription, switching, unlink and a clean new cycle', async ({ page, browser }) => {
 test.setTimeout(180000)
 const h = await createLifecycleBrowserDatabase()
 const studentContext = await browser.newContext({ baseURL: test.info().project.use.baseURL, viewport: page.viewportSize() })
 const student = await studentContext.newPage()
 try {
  await h.db.exec(`insert into auth.users(id) values('${USER}'),('${STUDENT}'); insert into public.user_roles(user_id,role) values('${USER}','professional'); insert into public.professional_profiles(user_id,professional_name) values('${USER}','Profissional Teste'); update public.profiles set display_name='João Silva' where id='${STUDENT}';`)
  const state = stateFixture(); state.routines[0].id = personalRoutine; state.week = Object.fromEntries(Array.from({ length: 7 }, (_, day) => [day, personalRoutine]))
  for (const actor of [USER, STUDENT]) await h.rpc(actor, 'save_account_preferences', { p_expected_revision: 0, p_display_unit: 'kg', p_preferences: { profile: { ...state.profile, name: actor === STUDENT ? 'João Silva' : 'Profissional Teste' }, onboardingDone: true, pwaInstallPrompt: { dismissForever: true }, weighBeforeWorkout: false } })
  await h.rpc(STUDENT, 'save_athlete_plan', { p_expected_revision: 0, p_mode: 'weekly', p_schedule: { week: state.week, dayPlan: {} }, p_routines: [{ id: personalRoutine, title: 'Treino de teste', prescription: { ex: [{ id: '0025', sets: 1, reps: 10, weight: 20 }] } }] })
  await seed(page, { professional: true, rpc: h.browserRpc(USER) })
  await seed(student, { authenticated: true, userId: STUDENT, state, rpc: h.browserRpc(STUDENT) })
  const requestLink = async () => {
   await student.goto('/#/student/professionals/add?code=PROFISSIONALTESTE')
   await student.getByRole('button', { name: 'Solicitar vínculo', exact: true }).click()
   await expect(student.getByText('Solicitação enviada', { exact: true }).first()).toBeVisible()
   await expect(student.getByText('Aguardando resposta', { exact: true }).first()).toBeVisible()
  }
  const accept = async () => {
   await page.goto('/#/professional')
   const pending = page.getByRole('link').filter({ hasText: 'João Silva' }).filter({ hasText: 'Aguardando resposta' })
   await expect(pending).toBeVisible(); await pending.click()
   await expect(page.getByRole('heading', { name: 'João Silva', exact: true })).toBeVisible()
   await page.getByRole('button', { name: 'Aceitar', exact: true }).click()
   await expect(page.getByRole('button', { name: 'Aceito', exact: true })).toBeVisible()
   await expect(page).toHaveURL(/#\/professional$/)
   await page.goto('/#/professional/students')
   await expect(page.getByRole('button', { name: 'Ativos', exact: true })).toHaveAttribute('aria-pressed', 'true')
   await page.getByRole('link').filter({ hasText: 'João Silva' }).click()
  }
  await requestLink()
  await accept()
  const firstCycle = (await h.rpc(USER, 'professional_relationship_cycles', { p_student_id: STUDENT }))[0].id
  // Author a prescription through the actual professional editor and send via its confirmation.
  await page.getByRole('link', { name: 'Criar plano para João Silva', exact: true }).click()
  await page.getByRole('button', { name: 'Criar do zero', exact: true }).click()
  await page.getByRole('textbox', { name: 'Nome do plano' }).fill('Prescrição R1')
  await page.locator('.plan-section-head button').click()
  await page.locator('.routine-name').fill('Peito profissional')
  await page.getByRole('button', { name: 'Adicionar exercício', exact: true }).click()
  const picker = page.getByRole('dialog')
  await picker.getByRole('searchbox').fill('supino com barra')
  await picker.locator('.picker-item-main').filter({ hasText: 'Supino com barra' }).first().click()
  await picker.getByRole('button', { name: 'Adicionar exercício', exact: true }).click()
  await expect(picker.locator('.exercise-picker-preview')).toHaveCount(0)
  await picker.getByRole('button', { name: 'Pronto', exact: true }).click()
  await expect(page.locator('.training-exercise-card')).toHaveCount(1)
  for (const index of [0, 1, 3]) await page.locator('.routine-week-card button').nth(index).click()
  await page.locator('.routine-completion-actions').getByRole('button', { name: 'Pronto', exact: true }).click()
  await page.getByRole('button', { name: 'Enviar ao aluno', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'Enviar plano', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('Plano enviado ao aluno', { exact: true })).toBeVisible()
  const applyProfessional = async () => {
   await student.goto('/#/plan')
   await tab(student, 'Treino do profissional').click()
   await student.getByRole('button', { name: 'Usar este plano', exact: true }).click()
   await student.getByRole('dialog').getByRole('button', { name: 'Aplicar plano', exact: true }).click()
   await expect(student.getByRole('dialog')).toHaveCount(0)
   await expect(tab(student, 'Treino do profissional')).toHaveAttribute('aria-pressed', 'true')
  }
  await applyProfessional()
  const calendar = student.locator('.plan-view > .training-plan-workspace .plan-week-card')
  await expect(calendar.getByRole('button', { name: 'Segunda-feira: Peito profissional', exact: true })).toBeVisible()
  await expect(calendar.getByRole('button', { name: 'Quarta-feira: Descanso', exact: true })).toBeVisible()
  await student.goto('/#/home'); await openMainNavigation(student); await student.locator('[data-tab-key="start"]').click()
  await expect(student.locator('.workout-session-title')).toContainText('Peito profissional')
  const active = await student.evaluate(user => JSON.parse(localStorage.getItem(`fpp_account_cache_v1:${user}`)).state.active, STUDENT)
  expect(active.entries[0].id).toBe('0025')
  await student.goto('/#/plan'); await tab(student, 'Meus treinos').click()
  await student.getByRole('button', { name: 'Usar meus treinos', exact: true }).click()
  await student.getByRole('dialog').getByRole('button', { name: 'Aplicar meus treinos', exact: true }).click()
  await expect(student.getByRole('dialog')).toHaveCount(0)
  await expect(tab(student, 'Meus treinos')).toHaveAttribute('aria-pressed', 'true')
  await expect(calendar).toContainText('Treino de teste')
  await applyProfessional()
  await page.goto(`/#/professional/students/${STUDENT}?section=relationship`)
  await page.getByRole('button', { name: 'Encerrar vínculo', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Encerrar vínculo', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText(/Vínculo encerrado ·/)).toBeVisible()
  // The student's next sync receives the fallback already persisted by the professional.
  await student.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(student.getByRole('group', { name: 'Escolher plano', exact: true })).toHaveCount(0)
  await expect(calendar).toContainText('Treino de teste')
  expect((await h.rpc(STUDENT, 'athlete_plan_library_page')).items.some(item => item.source_type === 'professional')).toBe(false)
  await page.goto('/#/professional/students?status=inactive')
  await expect(page.getByRole('link').filter({ hasText: 'João Silva' })).toContainText('Vínculo encerrado')
  await requestLink(); await accept()
  const cycles = await h.rpc(USER, 'professional_relationship_cycles', { p_student_id: STUDENT })
  expect(cycles).toHaveLength(2)
  expect(cycles.find(cycle => cycle.status === 'active').id).not.toBe(firstCycle)
  await page.getByRole('link', { name: 'Vínculo', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Vínculo atual', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Histórico', exact: true })).toBeVisible()
  await student.goto('/#/plan')
  await expect(student.getByRole('button', { name: 'Usar este plano', exact: true })).toHaveCount(0)
  await expect(calendar).toContainText('Treino de teste')
 } finally { await studentContext.close(); await h.close() }
})
