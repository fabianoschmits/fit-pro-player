#!/usr/bin/env node
// Generates the committed Brazilian Portuguese exercise-instruction pack.
// Source: dverzolla/exercises-dataset PR #64 (MIT-licensed instruction text).
// The upstream commit is pinned so regeneration is reproducible and cannot silently drift.

import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { EXDB } from '../src/lib/exercises-data.js'

const SOURCE_COMMIT = '01823800f6980ec54b6f566d73634551a5125253'
const SOURCE_URL = `https://raw.githubusercontent.com/dverzolla/exercises-dataset/${SOURCE_COMMIT}/data/exercises.json`
const output = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'instr', 'pt.js')

const response = await fetch(SOURCE_URL)
if (!response.ok) throw new Error(`Could not download PT-BR instructions: HTTP ${response.status}`)
const source = await response.json()

const byId = new Map(source.map(exercise => [String(exercise.id).padStart(4, '0'), exercise]))
const pack = {}
for (const exercise of EXDB) {
  const steps = byId.get(exercise.id)?.instruction_steps?.pt
  if (!Array.isArray(steps) || !steps.length || steps.some(step => typeof step !== 'string' || !step.trim())) {
    throw new Error(`Missing Brazilian Portuguese instructions for exercise ${exercise.id}`)
  }
  pack[exercise.id] = steps
}

if (Object.keys(pack).length !== EXDB.length) {
  throw new Error(`Instruction count mismatch: ${Object.keys(pack).length}/${EXDB.length}`)
}

const header = `// Generated by scripts/generate-pt-instructions.mjs.\n// PT-BR translation: dverzolla/exercises-dataset@${SOURCE_COMMIT} (MIT).\n`
await writeFile(output, `${header}export default ${JSON.stringify(pack)}\n`, 'utf8')
console.log(`Generated ${Object.keys(pack).length} PT-BR exercise instruction sets at ${output}`)
