const replacePhrase = (source, from, to) => source.replace(new RegExp(`(^|[^a-z])${from.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?=$|[^a-z])`, 'g'), (_, lead) => lead + to)

function translateName(original) {
  if (exact[original]) return exact[original]
  let name = original.toLowerCase()
    .replace(/(?<=\p{L})-(?=\p{L})/gu, ' ')
    .replace(/\bv\.?\s*(\d+)\b/g, 'versão $1')
  let suffix = ''
  for (const [prefix, translated] of equipmentPrefixes) {
    if (name.startsWith(prefix)) {
      name = name.slice(prefix.length)
      suffix = translated
      break
    }
  }
  let movement = ''
  for (const [source, translated] of Object.entries(movements).sort((a, b) => b[0].length - a[0].length)) {
    const next = replacePhrase(name, source, ' ')
    if (next !== name) {
      name = next
      movement = translated
      break
    }
  }
  for (const [from, to] of Object.entries(phrases).sort((a, b) => b[0].length - a[0].length)) name = replacePhrase(name, from, to)
  name = name.replace(/\p{L}+/gu, word => words[word] || word)
  name = name
    .replace(/\s+/g, ' ')
    .replace(/\s+([),])/g, '$1')
    .replace(/([(])\s+/g, '$1')
    .replace(/\bde de\b/g, 'de')
    .replace(/\bcom com\b/g, 'com')
    .replace(/\bno no\b/g, 'no')
    .trim()
  return [movement, name, suffix].filter(Boolean).join(' ')
}

const names = Object.fromEntries(EXDB.map(exercise => [exercise.id, translateName(exercise.n)]))
const unresolved = new Map()
for (const exercise of EXDB) {
  const translated = names[exercise.id]
  for (const word of translated.match(/[a-z]+/g) || []) {
    if (proper.has(word)) continue
    // Words that survived unchanged from the source are likely missing from the glossary.
    if ((exercise.n.toLowerCase().match(/[a-z]+/g) || []).includes(word) && !Object.values(words).join(' ').includes(word)) {
      unresolved.set(word, (unresolved.get(word) || 0) + 1)
    }
  }
}

