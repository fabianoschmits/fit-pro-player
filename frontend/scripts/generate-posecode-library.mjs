#!/usr/bin/env node
// Vendors the openly licensed Posecode movement examples used by the offline 3D player.
// The commit is pinned so builds never fetch code and regeneration cannot silently drift.

import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE_COMMIT = '579d986c3f8bf1f59414692dd2a0bbe4d867dc4a'
const EXAMPLES = [
  'arm-circles', 'bent-over-row', 'biceps-curl', 'bicycle-crunch', 'box-squat',
  'box-step-taps', 'box-step', 'chair-pose', 'chair-sit-to-stand', 'chest-opener',
  'cobra', 'cross-body-reach', 'crunch', 'dead-bug', 'dead-hang', 'deadlift',
  'elbow-flexion-pronation', 'forward-fold', 'forward-lunge', 'front-kick',
  'glute-bridge', 'good-morning', 'hanging-knee-raise', 'heel-raises',
  'high-knee-march', 'hip-abduction', 'hip-flexion-demo', 'jumping-jacks',
  'knee-flexion-demo', 'lateral-raise', 'mountain-climber', 'neck-rotation',
  'neck-side-stretch', 'overhead-reach-reset', 'pinch-grip', 'plank-hold',
  'pull-up', 'seated-forward-fold', 'seated-torso-twist',
  'shoulder-abduction-demo', 'shoulder-blade-retraction', 'shoulder-rolls',
  'shoulder-stretch', 'side-bend', 'single-leg-calf-raise', 'spinal-twist',
  'squat', 'standing-hamstring-curl', 'standing-quad-stretch', 'step-up',
  'superman', 'supine-leg-raise', 'touch-toes', 'triceps-dips', 'walk-cycle',
  'wall-sit', 'wrist-forearm-rolls',
]

const base = `https://raw.githubusercontent.com/posecode-dev/posecode/${SOURCE_COMMIT}/spec/examples/`
const entries = await Promise.all(EXAMPLES.map(async name => {
  const response = await fetch(`${base}${name}.posecode`)
  if (!response.ok) throw new Error(`Could not download ${name}: HTTP ${response.status}`)
  return [name, (await response.text()).trim()]
}))

const output = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'generated', 'exercise-motions.js')
const header = `// Generated by scripts/generate-posecode-library.mjs.\n// Posecode examples @ ${SOURCE_COMMIT} (Apache-2.0). No runtime network dependency.\n`
await writeFile(output, `${header}export default ${JSON.stringify(Object.fromEntries(entries), null, 2)}\n`, 'utf8')
console.log(`Generated ${entries.length} embedded Posecode movement profiles at ${output}`)
