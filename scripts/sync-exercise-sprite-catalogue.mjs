// Snapshot the frontend's validated sprites for database prescription guards.
// After importing sprites, run this command and deploy the resulting migration with the app.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { EXERCISE_SPRITE_EXERCISE_IDS } from '../frontend/src/lib/exercise-guide-assets.js'

const directory = fileURLToPath(new URL('../supabase/migrations/', import.meta.url))
const files = readdirSync(directory).filter(name => name.endsWith('_exercise_sprite_catalogue.sql')).sort()
const ids = [...EXERCISE_SPRITE_EXERCISE_IDS].sort()
const rows = ids.map(id => `  ('${id}')`).join(',\n')
const sql = `-- Generated by scripts/sync-exercise-sprite-catalogue.mjs. Do not edit.\n-- Only movements with validated local PNG sprites may be prescribed.\ndelete from public.exercise_sprite_catalogue;\ninsert into public.exercise_sprite_catalogue(exercise_id) values\n${rows};\n`
const previous = files.at(-1)
const matches = previous && readFileSync(directory + previous, 'utf8') === sql
if (process.argv.includes('--check')) {
  if (!matches) throw new Error('Sprite catalogue changed. Run node scripts/sync-exercise-sprite-catalogue.mjs and deploy the new migration.')
  console.log(`PASS database sprite catalogue matches all ${ids.length} available exercises`)
} else if (matches) {
  console.log(`Sprite catalogue already matches all ${ids.length} available exercises`)
} else {
  const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14)
  if (previous && stamp <= previous.split('_')[0]) throw new Error('Migration timestamp must be newer than the last catalogue snapshot.')
  const name = `${stamp}_exercise_sprite_catalogue.sql`
  writeFileSync(directory + name, sql, { flag: 'wx' })
  console.log(`Created ${name} with ${ids.length} available exercises`)
}
