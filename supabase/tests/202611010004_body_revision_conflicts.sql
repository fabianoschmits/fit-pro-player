begin;
create function pg_temp.assert_true(v boolean,m text) returns void language plpgsql as $$begin if v is distinct from true then raise exception 'assertion failed: %',m; end if; end$$;
create function pg_temp.error(q text,s text) returns void language plpgsql as $$declare got text; begin begin execute q; exception when others then got:=sqlstate; end; if got is distinct from s then raise exception 'expected %, got % for %',s,got,q; end if; end$$;
do $$declare u uuid:=gen_random_uuid(); other_id uuid:=gen_random_uuid(); w uuid:=gen_random_uuid(); m uuid:=gen_random_uuid(); w2 uuid:=gen_random_uuid(); m2 uuid:=gen_random_uuid(); a jsonb; b jsonb; weights jsonb; measures jsonb;
begin
 insert into auth.users(id) values(u),(other_id);
 perform set_config('request.jwt.claim.sub',u::text,true); set local role authenticated;
 a:=public.load_athlete_body(); b:=a;
 perform pg_temp.assert_true((a->>'revision')::bigint=0,'new body revision zero');
 weights:=jsonb_build_array(jsonb_build_object('id',w,'date','2026-11-01','weightKg',80));
 measures:=jsonb_build_array(jsonb_build_object('id',m,'date','2026-11-01','valuesCm','{"waist":80}'::jsonb,'note','first'));
 a:=public.save_athlete_body((a->>'revision')::bigint,weights,measures);
 perform pg_temp.assert_true(jsonb_array_length(a->'weights')=1 and jsonb_array_length(a->'measurements')=1,'atomic weights and measures saved');
 perform pg_temp.error(format('select public.save_athlete_body(%s,%L,%L)',b->>'revision','[]','[]'),'40001');
 perform pg_temp.assert_true(public.load_athlete_body()=a,'stale second device leaves both domains unchanged');
 perform public.save_athlete_body('[]','[]');
 a:=public.load_athlete_body();
 perform pg_temp.assert_true(jsonb_array_length(a->'weights')=1 and jsonb_array_length(a->'measurements')=1,'legacy empty snapshot cannot wipe');
 perform public.save_athlete_body(jsonb_build_array(jsonb_build_object('id',w2,'date','2026-11-02','weightKg',81)),jsonb_build_array(jsonb_build_object('id',m2,'date','2026-11-02','valuesCm','{"waist":81}'::jsonb)));
 a:=public.load_athlete_body();
 perform pg_temp.assert_true(jsonb_array_length(a->'weights')=2 and jsonb_array_length(a->'measurements')=2,'legacy append preserves omitted records');
 perform pg_temp.error(format('select public.save_athlete_body(%L,%L)',jsonb_set(weights,'{0,weightKg}','99'),'[]'),'40001');
 perform pg_temp.error(format('select public.save_athlete_body(%L,%L)','[]',jsonb_set(measures,'{0,note}','"changed"')),'40001');
 perform pg_temp.assert_true(public.load_athlete_body()=a,'legacy edits fail atomically');
 b:=public.save_athlete_body((a->>'revision')::bigint,weights,measures);
 perform pg_temp.assert_true(jsonb_array_length(b->'weights')=1 and jsonb_array_length(b->'measurements')=1,'current revision permits explicit removals');
 perform pg_temp.error('select public.save_athlete_body(-1,''[]'',''[]'')','22023');
 perform pg_temp.error('insert into public.bodyweight_entries(id,user_id,measured_on,weight_kg) values(gen_random_uuid(),auth.uid(),current_date,70)','42501');
 perform set_config('request.jwt.claim.sub',other_id::text,true);
 perform pg_temp.assert_true((public.load_athlete_body()->>'revision')::bigint=0,'body snapshots isolated by account');
 reset role;
end$$;
rollback;
